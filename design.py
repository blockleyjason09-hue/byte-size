def vars_block(d, indent="  "):
    return "\n".join("%s--%s: %s;" % (indent, k.replace("_", "-"), v) for k, v in d.items())


def build_css():
    return CSS.substitute(
        google=FONTS["google"], head=FONTS["head"], body=FONTS["body"], maths=FONTS["maths"], code=FONTS["code"],
        light=vars_block(TOKENS["light"]), dark=vars_block(TOKENS["dark"], "    "),
        **SHAPE)


FONT_LINK = re.compile(r'\s*<link rel="stylesheet" href="https://fonts\.googleapis\.com/css2\?[^"]*">')
STYLE_LINK = re.compile(r'(<link rel="stylesheet" href="style\.css(\?v=[^"]*)?">)')


def patch_html(path, check):
    s = open(path, encoding="utf-8").read()
    t = FONT_LINK.sub("", s)
    if "theme.css" not in t:
        t = STYLE_LINK.sub(lambda m: m.group(1) + '\n<link rel="stylesheet" href="theme.css' + (m.group(2) or '') + '">', t, count=1)
    if t != s:
        if not check:
            open(path, "w", encoding="utf-8").write(t)
        return True
    return False


def main():
    check = "--check" in sys.argv
    css = build_css()
    out = os.path.join(HERE, "theme.css")
    old = open(out, encoding="utf-8").read() if os.path.exists(out) else ""
    if css != old and not check:
        open(out, "w", encoding="utf-8").write(css)
    changed = [os.path.basename(p) for p in sorted(glob.glob(os.path.join(HERE, "*.html"))) if patch_html(p, check)]
    print("theme.css", "unchanged" if css == old else ("would change" if check else "written"))
    print("pages updated:", ", ".join(changed) if changed else "none")


if __name__ == "__main__":
    main()
